        const index = createToolkitIndex({
          toolkits,
          typeableTools: { withTypes: false, tools: [] },
          triggerTypes: [],
          versionMap,
        });

        const sources = generatePythonToolkitSources(BANNER)(index);
        expect(sources).toHaveLength(2);

